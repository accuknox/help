"""Import a Salesforce export (Account, Contact, Opportunity CSVs) into the CRM REST API.

Scope "pipeline": every opportunity, the accounts those opportunities belong to, and
the contacts at those accounts. Scope "all": every row in the three files.

The run is resumable. state.json maps each Salesforce Id to the CRM id it produced,
so a rerun skips finished work. Every failure goes to errors.csv with the reason.

Environment:
    CRM_API_KEY               the CRM key (never commit it)
    CRM_DEFAULT_OWNER_EMAIL   the CRM user who owns deals with no matching owner
    CRM_IMPORT_DIR            the folder with the three CSVs (default: current folder)

Usage:
    python salesforce_import.py --dry-run    # map everything, write nothing
    python salesforce_import.py --limit 5    # pilot: 5 opportunities and their records
    python salesforce_import.py              # full run in the chosen scope
"""

