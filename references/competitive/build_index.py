"""Regenerate references/competitive/INDEX.md from what is on disk.

    python references/competitive/build_index.py

Run it after every new comparison page, workbook, PDF or battlecard. It reads these places:

  references/drafts/comparison/*.md        comparison page drafts (frontmatter)
  references/competitive/aspm-comparisons/ ASPM versus pages (frontmatter)
  references/competitive/battlecards/      workbooks, per-competitor folders, engine PDFs
  references/competitive/*.md              research notes
  references/product-research/             PRD and market research that includes competitor work

INDEX.md is generated. Edit this script, never the file.
"""

import datetime
import json
import re
from pathlib import Path

HERE = Path(__file__).parent
REFS = HERE.parent
CARDS = HERE / "battlecards"
SKIP = {"build", "assets", "research", "data", "vendors_v2", "vendors_v3", "__pycache__", "_tmp"}


def rel(p: Path) -> str:
    return p.relative_to(REFS).as_posix()


def frontmatter(p: Path) -> dict:
    t = p.read_text(encoding="utf-8", errors="replace")
    m = re.match(r"---\n(.*?)\n---", t, re.S)
    out = {}
    if m:
        for line in m.group(1).splitlines():
            k, _, v = line.partition(":")
            out[k.strip()] = v.strip().strip('"')
    return out


def table(headers, rows):
    if not rows:
        return "None yet.\n"
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def pages_from(folder: Path):
    rows = []
    for p in sorted(folder.glob("*.md")):
        fm = frontmatter(p)
        if fm.get("title"):
            rows.append([fm["title"], fm.get("category", ""), fm.get("archetype", ""), fm.get("parameter_count", ""), f"`{rel(p)}`"])
    return rows


def main():
    engine_pdfs, other_pdfs, workbooks = [], [], []
    meta_files = sorted(CARDS.rglob("*.meta.json"))
    engine_names = set()
    for m in meta_files:
        d = json.loads(m.read_text(encoding="utf-8"))
        pdf = m.with_name(d["file"])
        engine_names.add(pdf.resolve())
        engine_pdfs.append([d["title"], ", ".join(d["vendors"]), d.get("category", ""), d["pages"], d["built"], f"`{rel(pdf)}`", f"`{rel(m.parent)}/`"])

    for p in sorted(CARDS.rglob("*.pdf")):
        if p.resolve() in engine_names or any(part in SKIP for part in p.relative_to(CARDS).parts[:-1]):
            continue
        other_pdfs.append([p.parent.name if p.parent != CARDS else "(root)", f"`{rel(p)}`"])
    for p in sorted(CARDS.rglob("*.xlsx")):
        if any(part in SKIP for part in p.relative_to(CARDS).parts[:-1]):
            continue
        workbooks.append([f"`{rel(p)}`"])

    competitor_dirs = []
    for d in sorted(x for x in CARDS.iterdir() if x.is_dir()):
        pdfs = [f for f in d.glob("*.pdf")]
        competitor_dirs.append([d.name, len(pdfs), len(list(d.glob("*.md"))), f"`{rel(d)}/`"])

    notes = [[f"`{rel(p)}`"] for p in sorted(HERE.glob("*.md")) if p.name not in ("INDEX.md", "README.md")]
    research = []
    pr = REFS / "product-research"
    if pr.exists():
        for d in sorted(x for x in pr.iterdir() if x.is_dir()):
            research.append([f"`{rel(d)}/`", len([f for f in d.rglob("*") if f.is_file()])])

    parts = [
        "# Competitive Index\n",
        "Generated by `references/competitive/build_index.py`. Do not edit by hand. Paths are relative to",
        f"`references/`. Last built {datetime.date.today().isoformat()}.\n",
        "The live pages on accuknox.com are on the [comparisons hub](https://accuknox.com/comparisons).",
        "This index covers the working files in this repo.\n",
        "## Detailed Comparison PDFs Come From the Shared Engine\n",
        table(["Title", "Vendors", "Category", "Pages", "Built", "File", "Set folder"], engine_pdfs),
        "## Per-Competitor Battlecard Folders Hold Data, Builders and PDFs\n",
        table(["Folder", "PDFs", "Markdown", "Path"], competitor_dirs),
        "## Other Battlecard PDFs\n",
        table(["Folder", "File"], other_pdfs),
        "## Comparison Workbooks\n",
        table(["File"], workbooks),
        "## Comparison Page Drafts for accuknox.com\n",
        table(["Title", "Category", "Archetype", "Rows", "File"], pages_from(REFS / "drafts" / "comparison")),
        "## ASPM Versus Pages\n",
        table(["Title", "Category", "Archetype", "Rows", "File"], pages_from(HERE / "aspm-comparisons")),
        "## Research Notes\n",
        table(["File"], notes),
        "## Product Research Holds Competitor Teardowns\n",
        table(["Folder", "Files"], research),
    ]
    (HERE / "INDEX.md").write_text("\n".join(parts), encoding="utf-8")
    print(f"INDEX.md: {len(engine_pdfs)} engine PDFs, {len(competitor_dirs)} competitor folders, {len(other_pdfs)} other PDFs, {len(workbooks)} workbooks")


if __name__ == "__main__":
    main()
